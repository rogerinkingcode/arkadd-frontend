/** Lê `a.b.c` na árvore. Devolve `null` quando o caminho não existe ou não termina em texto. */
export function lookup(tree: Tree, path: string): string | null {
    const value = path.split(".").reduce<Leaf | Tree | undefined>((node, key) => (typeof node === "object" && node !== null ? node[key] : undefined), tree);

    return typeof value === "string" ? value : null;
}
